def gen_frame():
    """
    GEPRC Mark4 7" V2 frame.
    Wheelbase: ~295mm (motor-to-motor), arms at 45°.
    Top/bottom plates: ~170×170mm, 2mm thick, z=0 and z=25mm.
    Arms: 15mm wide, 5mm thick.
    """
    tris = []
    plate_size = 170
    plate_thick = 2.5
    arm_w = 15
    arm_thick = 5
    stack_h = 25  # gap between plates

    # Bottom plate
    tris += box(0, 0, -plate_thick/2, plate_size, plate_size, plate_thick)
    # Top plate
    tris += box(0, 0, stack_h + plate_thick/2, plate_size, plate_size, plate_thick)

    # 4 arms at 45°, motor centres at ~147.5mm from centre
    motor_r = 147.5
    for angle_deg in [45, 135, 225, 315]:
        a = math.radians(angle_deg)
        mx = motor_r * math.cos(a)
        my = motor_r * math.sin(a)
        tris += arm(0, 0, mx, my, 0, arm_thick, arm_w)
        # motor mount pad at tip
        tris += cylinder(mx, my, arm_thick, arm_thick+6, 15, 16)

    return tris


