def gen_print_camera_bracket():
    """
    IMX219 belly camera bracket — T-drop design.

    Frame side (top):  flat plate, 2x M3 holes at ±10.95mm (= 21.9mm spacing)
    Camera side (bot): flat plate, 2x M2 holes at ±13.8mm  (= 27.6mm spacing)
    Drop height: 22mm so camera clears belly plate and faces forward-level.

    Side profile:
        ─────────────────────  frame belly plate (reference)
        [  top mount plate  ]  4mm thick, 36×12mm
               │ drop post │   8×8mm, 22mm tall
        [  cam mount plate  ]  4mm thick, 44×30mm
        [   IMX219 PCB      ]  (not part of bracket)

    Top plate bolt centres: y=0, x=±10.95mm
    Bottom plate bolt centres: y=0, x=±13.8mm
    """
    tris = []

    # Top mounting plate (bolts to frame belly, flat top face at z=0)
    tris += box(0, 0, -2, 36, 12, 4)

    # Bolt boss stubs on top plate (M3, visual only — no hole in STL)
    for bx in [10.95, -10.95]:
        tris += cylinder(bx, 0, 0, 3, 3.5, 12)   # small boss, 3mm above plate

    # Vertical drop post (centred, 8×8mm cross-section, 22mm tall)
    tris += box(0, 0, -2 - 11, 8, 8, 22)

    # Bottom camera mount plate (flat bottom face)
    plate_bot_z = -2 - 22  # bottom of drop post
    tris += box(0, 0, plate_bot_z - 2, 44, 30, 4)

    # Camera bolt boss stubs on bottom plate (M2, visual only)
    for bx in [13.8, -13.8]:
        tris += cylinder(bx, 0, plate_bot_z - 4, plate_bot_z - 1, 2.5, 12)

    return tris


def gen_print_cone():
    """
    Traffic cone — 150mm tall, 60mm base radius, ~8mm tip radius.
    """
    tris = []
    h = 150
    r_base = 60
    r_tip = 8
    segs = 32
    base_thick = 8  # flat base disc
    # Conical body (approximated as tube stack or cylinder taper via triangle fan)
    # Build as a tapered cylinder using triangle strips
    angles = [2 * math.pi * i / segs for i in range(segs)]
    # Base ring cap
    cb = (0, 0, base_thick)
    pts_base = [(r_base * math.cos(a), r_base * math.sin(a), base_thick) for a in angles]
    pts_top  = [(r_tip  * math.cos(a), r_tip  * math.sin(a), base_thick + h) for a in angles]
    ct = (0, 0, base_thick + h)
    for i in range(segs):
        j = (i + 1) % segs
        # bottom cap
        tris.append(((0, 0, -1), cb, pts_base[j], pts_base[i]))
        # top cap
        tris.append(((0, 0, 1), ct, pts_top[i], pts_top[j]))
        # side face
        p0, p1, p2, p3 = pts_base[i], pts_base[j], pts_top[j], pts_top[i]
        n = _normal(p0, p1, p2)
        tris.append((n, p0, p1, p2))
        tris.append((n, p0, p2, p3))
    # Flat base disc
    tris += cylinder(0, 0, 0, base_thick, r_base, segs)
    return tris


