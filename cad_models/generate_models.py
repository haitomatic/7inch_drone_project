# Primitive builders
# ---------------------------------------------------------------------------

def _normal(v1, v2, v3):
    ax, ay, az = v2[0]-v1[0], v2[1]-v1[1], v2[2]-v1[2]
    bx, by, bz = v3[0]-v1[0], v3[1]-v1[1], v3[2]-v1[2]
    nx = ay*bz - az*by
    ny = az*bx - ax*bz
    nz = ax*by - ay*bx
    L = math.sqrt(nx*nx + ny*ny + nz*nz) or 1.0
    return (nx/L, ny/L, nz/L)


def box(cx, cy, cz, dx, dy, dz):
    """Axis-aligned box centred at (cx,cy,cz) with dimensions dx×dy×dz."""
    x0, x1 = cx - dx/2, cx + dx/2
    y0, y1 = cy - dy/2, cy + dy/2
    z0, z1 = cz - dz/2, cz + dz/2
    quads = [
        ((0, 0,-1), (x0,y0,z0),(x1,y0,z0),(x1,y1,z0),(x0,y1,z0)),
        ((0, 0, 1), (x0,y0,z1),(x0,y1,z1),(x1,y1,z1),(x1,y0,z1)),
        ((0,-1, 0), (x0,y0,z0),(x0,y0,z1),(x1,y0,z1),(x1,y0,z0)),
        ((0, 1, 0), (x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)),
        ((-1,0, 0), (x0,y0,z0),(x0,y1,z0),(x0,y1,z1),(x0,y0,z1)),
        (( 1,0, 0), (x1,y0,z0),(x1,y0,z1),(x1,y1,z1),(x1,y1,z0)),
    ]
    tris = []
    for n, p0, p1, p2, p3 in quads:
        tris.append((n, p0, p1, p2))
        tris.append((n, p0, p2, p3))
    return tris


def cylinder(cx, cy, z0, z1, r, segs=32):
    """Vertical cylinder from z0 to z1, radius r, centred at cx,cy."""
    tris = []
    angles = [2*math.pi*i/segs for i in range(segs)]
    pts_bot = [(cx + r*math.cos(a), cy + r*math.sin(a), z0) for a in angles]
    pts_top = [(cx + r*math.cos(a), cy + r*math.sin(a), z1) for a in angles]
    cb, ct = (cx, cy, z0), (cx, cy, z1)
    for i in range(segs):
        j = (i+1) % segs
        # bottom cap
        n = (0, 0, -1)
        tris.append((n, cb, pts_bot[j], pts_bot[i]))
        # top cap
        n = (0, 0, 1)
        tris.append((n, ct, pts_top[i], pts_top[j]))
        # side
        p0, p1, p2, p3 = pts_bot[i], pts_bot[j], pts_top[j], pts_top[i]
        n = _normal(p0, p1, p2)
        tris.append((n, p0, p1, p2))
        tris.append((n, p0, p2, p3))
    return tris


def tube(cx, cy, z0, z1, r_out, r_in, segs=32):
    """Hollow cylinder (tube) for motor bell detail."""
    tris = []
    angles = [2*math.pi*i/segs for i in range(segs)]
    outer_bot = [(cx + r_out*math.cos(a), cy + r_out*math.sin(a), z0) for a in angles]
    outer_top = [(cx + r_out*math.cos(a), cy + r_out*math.sin(a), z1) for a in angles]
    inner_bot = [(cx + r_in*math.cos(a),  cy + r_in*math.sin(a),  z0) for a in angles]
    inner_top = [(cx + r_in*math.cos(a),  cy + r_in*math.sin(a),  z1) for a in angles]
    for i in range(segs):
        j = (i+1) % segs
        # outer side
        p0,p1,p2,p3 = outer_bot[i],outer_bot[j],outer_top[j],outer_top[i]
        n = _normal(p0,p1,p2)
        tris += [(n,p0,p1,p2),(n,p0,p2,p3)]
        # inner side (reversed winding)
        p0,p1,p2,p3 = inner_bot[i],inner_top[i],inner_top[j],inner_bot[j]
        n = _normal(p0,p1,p2)
        tris += [(n,p0,p1,p2),(n,p0,p2,p3)]
        # bottom ring
        p0,p1,p2,p3 = outer_bot[i],inner_bot[i],inner_bot[j],outer_bot[j]
        n = (0,0,-1)
        tris += [(n,p0,p1,p2),(n,p0,p2,p3)]
        # top ring
        p0,p1,p2,p3 = outer_top[i],outer_top[j],inner_top[j],inner_top[i]
        n = (0,0,1)
        tris += [(n,p0,p1,p2),(n,p0,p2,p3)]
    return tris


def disc(cx, cy, z, r, thickness=1.5, segs=48):
    """Flat disc (propeller plane)."""
    return cylinder(cx, cy, z - thickness/2, z + thickness/2, r, segs)


def arm(cx1, cy1, cx2, cy2, z0, z1, width):
    """Rectangular arm from point 1 to point 2."""
    dx = cx2 - cx1
    dy = cy2 - cy1
    length = math.sqrt(dx*dx + dy*dy)
    angle = math.atan2(dy, dx)
    # perpendicular half-width
    px = -math.sin(angle) * width/2
    py =  math.cos(angle) * width/2
    p = [
        (cx1+px, cy1+py, z0), (cx1-px, cy1-py, z0),
        (cx2-px, cy2-py, z0), (cx2+px, cy2+py, z0),
        (cx1+px, cy1+py, z1), (cx1-px, cy1-py, z1),
        (cx2-px, cy2-py, z1), (cx2+px, cy2+py, z1),
    ]
    tris = []
    faces = [
        ((0,0,-1), 0,1,2,3), ((0,0,1), 4,7,6,5),
        (None,     0,4,5,1), (None,    2,6,7,3),
        (None,     0,3,7,4), (None,    1,5,6,2),
    ]
    for entry in faces:
        if entry[0] is None:
            n_override = None
            i0,i1,i2,i3 = entry[1],entry[2],entry[3],entry[4]
        else:
            n_override, i0,i1,i2,i3 = entry
        q = [p[i0],p[i1],p[i2],p[i3]]
        n = n_override if n_override else _normal(q[0],q[1],q[2])
        tris.append((n,q[0],q[1],q[2]))
        tris.append((n,q[0],q[2],q[3]))
    return tris


