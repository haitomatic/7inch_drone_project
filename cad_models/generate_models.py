def gen_print_jetson_mount():
    """
    Jetson Orin Nano sliding mount — C-hook rail design.
    Jetson (100×79mm, ~3mm PCB) slides in from either side (X direction).
    Front and rear walls each have an inward-facing lip that retains the board.

    Cross-section (looking from X / slide-in direction):
        lip_depth=5mm inward
             ┌────┐         ┌────┐
             │ lip│         │lip │  Z=8–10mm
        ─────┘    │         │    └─────
        front wall│         │rear wall  Z=3–8mm
        ──────────┴─────────┴──────────  base Z=0–3mm
              ←── inner_y = 81mm ───→
    """
    inner_x   = 61    # slide-in direction — reduced by 20mm (was 81mm)
    inner_y   = 102   # front-rear direction — 1mm clearance over 100mm board length
    wall_t    = 3     # front/rear wall thickness
    base_t    = 3     # base plate thickness
    wall_h    = 5     # wall height above base plate
    lip_depth = 5     # lip extends this far inward (overhangs board by ~2mm)
    lip_h     = 2     # lip vertical thickness
    outer_x   = inner_x + 2 * wall_t   # 108mm total width

    tris = []

    # Base plate
    tris += box(0, 0, base_t / 2,
                outer_x, inner_y + 2 * wall_t, base_t)

    # Front wall (+Y)
    fy = inner_y / 2 + wall_t / 2
    tris += box(0,  fy, base_t + wall_h / 2, outer_x, wall_t, wall_h)
    tris += box(0, -fy, base_t + wall_h / 2, outer_x, wall_t, wall_h)

    # Front lip — inward from top of front wall
    lip_cy = inner_y / 2 + wall_t - lip_depth / 2
    tris += box(0,  lip_cy, base_t + wall_h + lip_h / 2, outer_x, lip_depth, lip_h)
    tris += box(0, -lip_cy, base_t + wall_h + lip_h / 2, outer_x, lip_depth, lip_h)

    return tris


