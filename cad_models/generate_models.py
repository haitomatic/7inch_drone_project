"""
EmberWatch Drone Assembly — STL Model Generator
Generates approximate-dimension STL files for the 10 largest components.
All units in mm. Run: python3 generate_models.py
"""

import struct
import math
import os

OUT_DIR = os.path.dirname(os.path.abspath(__file__))


# ---------------------------------------------------------------------------
# STL writer
# ---------------------------------------------------------------------------

def write_stl(filename, triangles):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "wb") as f:
        header = f"Generated by generate_models.py — {filename}".encode()
        f.write(header[:80].ljust(80, b" "))
        f.write(struct.pack("<I", len(triangles)))
        for normal, v1, v2, v3 in triangles:
            for v in (normal, v1, v2, v3):
                f.write(struct.pack("<3f", *v))
            f.write(struct.pack("<H", 0))
    print(f"  Wrote {len(triangles):5d} triangles → {filename}")


